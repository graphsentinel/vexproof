#!/usr/bin/env python3
"""FULL=1 path (scripts/lab.sh test with FULL=1, run once after the fast path): the measured methods re-run from
source on metrics-server v0.9.0, compared with the measured results.

  1. source     clone kubernetes-sigs/metrics-server v0.9.0, `go mod vendor` (golang image of the shipped build)
  2. ci         ci/vexproof.py: govulncheck, coverage rebuild, k3d (cluster vexproof-ci), the project's own manifest,
                workload, counters, Trivy, chains + OpenVEX. Compared: the status of every OSV the measured CI runs
                chained (a newer vulnerability database can add OSVs; they are listed, not compared)
  3. mode-b     kernel uprobes on the *official* image's binary in the same cluster (privileged DaemonSet), offsets
                from .gopclntab + the ELF program headers. Compared: the HTTP/2 server-side probes fire
  4. codeql     CodeQL database of the source (vendored code extracted), lab/codeql/sinkgen/batch.py --mode all-args
                (no LLM). Compared: the set of OSVs with a taint path
  5. cleanup    delete the vexproof-ci cluster
Writes results/full/summary.json ({"checks": [...]}) and exits 1 if a step failed or a check differs.

usage: full.py   (run from the project root; needs scripts/platform.sh install with FULL=1 and scripts/lab.sh install)
environment: ENGINE (docker | podman)
"""
import csv
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys
import time
import urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RT = os.path.join(ROOT, "lab", ".runtime", "full")
OUT = os.path.join(ROOT, "results", "full")
ENGINE = os.environ.get("ENGINE", "docker")
V = dict(ln.strip().split("=", 1) for ln in open(os.path.join(ROOT, "scripts", "versions.env"))
         if "=" in ln and not ln.lstrip().startswith("#"))
MS_REPO, MS_REF = "https://github.com/kubernetes-sigs/metrics-server", "v0.9.0"
MS_MANIFEST = f"{MS_REPO}/releases/download/{MS_REF}/components.yaml"
MS_MANIFEST_SHA256 = "1cec29a5267809306a2c6ec74a3e449abbb705b4a8beed0c8a1963910f72c79b"
GO_IMAGE = "docker.io/library/golang:1.26.8@sha256:eb36c1664dd974cde625f736e02c204383deebe03977365caaec5bf49f794348"
CLUSTER = "vexproof-ci"
KC = ["kubectl", "--context", f"k3d-{CLUSTER}"]
# Mode B probes (the measured set, evidence/reference/c7-modeB-metrics-server-v0.9.0/offsets.txt)
PROBES = {"vxb_framer_readmetaframe": "golang.org/x/net/http2.(*Framer).readMetaFrame",
          "vxb_serverconn_closestream": "golang.org/x/net/http2.(*serverConn).closeStream",
          "vxb_serverconn_processheaders": "golang.org/x/net/http2.(*serverConn).processHeaders",
          "vxb_clientconnreadloop_handleresponse": "golang.org/x/net/http2.(*clientConnReadLoop).handleResponse",
          "vxb_transport_roundtripopt": "golang.org/x/net/http2.(*Transport).RoundTripOpt",
          "vxb_transportresponsebody_read": "golang.org/x/net/http2.(*transportResponseBody).Read",
          # not in the measured set: the value method behind the autogenerated pointer wrapper above
          "vxb_transportresponsebody_read_value": "golang.org/x/net/http2.transportResponseBody.Read"}
SERVER_PROBES = ("vxb_framer_readmetaframe", "vxb_serverconn_closestream", "vxb_serverconn_processheaders")
checks, log = [], None


def sh(*a, check=True, cwd=None, env=None, inp=None):
    log.write(f"$ {' '.join(a)}\n")
    log.flush()
    p = subprocess.run(a, cwd=cwd, env=env, input=inp, capture_output=True, text=True)
    log.write(p.stdout[-6000:] + p.stderr[-6000:] + f"[rc={p.returncode}]\n")
    log.flush()
    if check and p.returncode:
        raise RuntimeError(f"failed: {' '.join(a[:5])}: {p.stderr[-800:]}")
    return p.stdout


def check(name, ok, observed):
    checks.append({"check": name, "ok": bool(ok), "observed": observed})
    print(f"  {'ok  ' if ok else 'FAIL'} {name}: {observed}", flush=True)


def step(name, fn):
    t = time.time()
    print(f"== {name}", flush=True)
    try:
        fn()
        check(f"step {name} completed", True, f"{round(time.time() - t)} s")
    except Exception as e:  # a failed step is a failed check; later steps still run if they can
        check(f"step {name} completed", False, str(e)[-400:])


# ---------------------------------------------------------------- 1. source
SRC = os.path.join(RT, "src", f"metrics-server-{MS_REF}")


def source():
    if not os.path.isdir(os.path.join(SRC, ".git")):
        shutil.rmtree(SRC, ignore_errors=True)
        sh("git", "clone", "-q", "--depth", "1", "--branch", MS_REF, MS_REPO, SRC)
    rev = sh("git", "-C", SRC, "rev-parse", "HEAD").strip()
    if not os.path.isdir(os.path.join(SRC, "vendor")):
        mod = os.path.join(RT, "gomod")
        os.makedirs(mod, exist_ok=True)
        sh(ENGINE, "run", "--rm", "-v", f"{SRC}:/src", "-v", f"{mod}:/go/pkg/mod", "-w", "/src", "-e", "GOTOOLCHAIN=local",
           GO_IMAGE, "go", "mod", "vendor")
    check("metrics-server source", True, f"{MS_REF} {rev[:12]}")
    data = urllib.request.urlopen(MS_MANIFEST).read()
    open(os.path.join(RT, "components.yaml"), "wb").write(data)
    check("release manifest sha256", hashlib.sha256(data).hexdigest() == MS_MANIFEST_SHA256, MS_MANIFEST)


# ---------------------------------------------------------------- 2. ci recipe
def ci():
    out = os.path.join(OUT, "ci")
    gobin = os.path.join(RT, "gobin")
    os.makedirs(gobin, exist_ok=True)
    shutil.copy(shutil.which("govulncheck"), os.path.join(gobin, "govulncheck"))
    cfg = json.load(open(os.path.join(ROOT, "ci", "metrics-server.json")))
    cfg.update(src=SRC, out=out, manifest=os.path.join(RT, "components.yaml"), engine=ENGINE, cluster=CLUSTER,
               gocache=os.path.join(RT, "gocache"), gomod=os.path.join(RT, "gomod"), gobin=gobin,
               trivycache=os.path.join(RT, "trivycache"), covdir=os.path.join(RT, "covdata"), delete_cluster=False)
    for d in ("gocache", "gomod", "trivycache"):
        os.makedirs(cfg[d], exist_ok=True)
    f = os.path.join(RT, "ci-config.json")
    json.dump(cfg, open(f, "w"), indent=1)
    rc = subprocess.run([sys.executable, os.path.join(ROOT, "ci", "vexproof.py"), f], capture_output=True, text=True)
    log.write(rc.stdout + rc.stderr)
    idx = os.path.join(out, "chains", "index.json")
    if not os.path.exists(idx):
        raise RuntimeError(f"ci/vexproof.py wrote no chains (exit {rc.returncode}); see results/full/ci/ci.log")
    got = {x["osv"]: f"{x['status']}|{x['justification'] or ''}" for x in json.load(open(idx))}
    want = {r["key"].rsplit("/", 1)[1]: r["expected"] for r in csv.DictReader(open(os.path.join(ROOT, "lab", "expected.tsv")),
                                                                               delimiter="\t")
            if r["kind"] == "chain" and r["key"].startswith("chains-ci-metrics-server-v0.9.0-r1/")}
    for osv, exp in sorted(want.items()):
        check(f"ci chain {osv} (measured {exp})", got.get(osv) == exp, got.get(osv, "not chained by today's database"))
    new = sorted(set(got) - set(want))
    check("ci chains for OSVs published after the measurement (listed, not compared)", True, new or "none")


# ---------------------------------------------------------------- 3. mode b
def file_offsets(binary, addrs):
    """virtual address -> file offset through the ELF64 PT_LOAD segments"""
    b = open(binary, "rb").read()
    phoff, = struct.unpack_from("<Q", b, 0x20)
    phentsize, phnum = struct.unpack_from("<HH", b, 0x36)
    segs = []
    for i in range(phnum):
        p_type, _, p_offset, p_vaddr, _, p_filesz = struct.unpack_from("<IIQQQQ", b, phoff + i * phentsize)
        if p_type == 1:
            segs.append((p_vaddr, p_offset, p_filesz))
    out = {}
    for name, a in addrs.items():
        seg = [s for s in segs if s[0] <= a < s[0] + s[2]]
        if not seg:
            raise RuntimeError(f"{name}: address {a:#x} in no PT_LOAD segment")
        out[name] = a - seg[0][0] + seg[0][1]
    return out


def mode_b():
    binary = os.path.join(ROOT, "lab", ".runtime", "cache", "bin", "metrics-server-v0.9.0", "metrics-server")
    listing = sh(os.path.join(ROOT, "lab", ".runtime", "bin", "pclnsym"), binary, *PROBES.values())
    addr = {}
    for ln in listing.splitlines():
        a, fn, _ = ln.split("\t")
        for probe, sym in PROBES.items():
            if fn == sym:
                addr[probe] = int(a, 16)
    missing = sorted(set(PROBES) - set(addr))
    if missing:
        raise RuntimeError(f"symbols not in the official binary: {missing}")
    offs = file_offsets(binary, addr)
    # the official image, unpatched except the k3d kubelet flag; pinned by digest
    sh(*KC, "-n", "kube-system", "delete", "deployment", "metrics-server", "--ignore-not-found", "--wait=true")
    sh(*KC, "apply", "-f", os.path.join(RT, "components.yaml"))
    patch = {"spec": {"template": {"spec": {"containers": [{"name": "metrics-server", "image": V["METRICS_SERVER_IMAGE"],
                                                             "args": json.load(open(os.path.join(ROOT, "ci", "metrics-server.json")))["args"]}]}}}}
    sh(*KC, "-n", "kube-system", "patch", "deployment", "metrics-server", "--type", "strategic", "-p", json.dumps(patch))
    sh(*KC, "-n", "kube-system", "rollout", "status", "deployment/metrics-server", "--timeout=240s")
    man = open(os.path.join(ROOT, "ci", "modeB-daemonset.yaml")).read()
    man = man.replace("    REPLACED_BY_SCRIPT", "\n".join(f"    {p} {o:#x}" for p, o in offs.items()))
    sh(*KC, "apply", "-f", "-", inp=man)
    sh(*KC, "-n", "vexproof-probe", "rollout", "status", "daemonset/uprobe", "--timeout=180s")
    for _ in range(60):
        if "probes enabled" in sh(*KC, "-n", "vexproof-probe", "logs", "-l", "app=vexproof-uprobe", "--tail=-1", check=False):
            break
        time.sleep(3)
    else:
        raise RuntimeError("probes not enabled")
    for cmd in json.load(open(os.path.join(ROOT, "ci", "metrics-server.json")))["exercise"]:
        if cmd.startswith("sleep "):
            time.sleep(int(cmd.split()[1]))
        else:
            sh(*KC, *cmd.split()[1:], check=False)
    text = ""
    for _ in range(80):
        text = sh(*KC, "-n", "vexproof-probe", "logs", "-l", "app=vexproof-uprobe", "--tail=-1", check=False)
        if "=== removed" in text:
            break
        time.sleep(3)
    open(os.path.join(OUT, "modeB-daemonset.log"), "w").write(text)
    prof = text.split("=== uprobe_profile", 1)[-1].split("=== removed", 1)[0]
    hits = {ln.split()[0]: int(ln.split()[1]) for ln in prof.strip().splitlines() if len(ln.split()) == 2}
    json.dump({"offsets": {p: hex(o) for p, o in offs.items()}, "hits": hits}, open(os.path.join(OUT, "modeB.json"), "w"), indent=1)
    for p in SERVER_PROBES:
        check(f"mode-b {p} fires on the official binary", hits.get(p, 0) > 0, hits.get(p))
    check("mode-b other probes (reported; 0 hits is not 'not executed')", True,
          {p: hits.get(p) for p in PROBES if p not in SERVER_PROBES})
    sh(*KC, "delete", "namespace", "vexproof-probe", "--wait=true", check=False)


# ---------------------------------------------------------------- 4. codeql
def codeql():
    db = os.path.join(RT, "codeql-db")
    import glob
    if not glob.glob(os.path.join(db, "db-go", "*.dbscheme")):  # missing or not finalized (an interrupted run)
        env = dict(os.environ, GOFLAGS="-mod=vendor", CGO_ENABLED="0")
        sh("codeql", "database", "create", db, "--language=go", f"--source-root={SRC}",
           "--extractor-option=go.extract_vendor_dirs=true", "--command=go build ./cmd/metrics-server", "--overwrite", env=env)
    work = os.path.join(ROOT, "lab", ".runtime", "work", "run-1")
    rep = os.path.join(work, "results", "report", "metrics-server-v0.9.0--metrics-server.json")
    if not os.path.exists(rep):
        raise RuntimeError("no fast-path report (run scripts/lab.sh test first)")
    goroot = sh("go", "env", "GOROOT").strip()
    out = os.path.join(OUT, "codeql")
    shutil.rmtree(out, ignore_errors=True)
    sh(sys.executable, os.path.join(ROOT, "lab", "codeql", "sinkgen", "batch.py"), "--mode", "all-args", "--report", rep,
       "--vendor", os.path.join(SRC, "vendor"), "--goroot", os.path.join(goroot, "src"), "--db", db, "--out", out,
       "--pclnsym", os.path.join(work, "evidence", "c9-autochain-metrics-server-v0.9.0", "pclnsym-all-metrics-server.txt"),
       cwd=work)
    res = json.load(open(os.path.join(out, "index.json")))["results"]
    meas = json.load(open(os.path.join(ROOT, "lab", ".runtime", "in", "evidence", "c11-codeql-batch",
                                       "metrics-server-v0.9.0--metrics-server-all-args", "index.json")))["results"]
    got = sorted(x["osv"] for x in res if x.get("taint_results"))
    want = sorted(x["osv"] for x in meas if x.get("taint_results"))
    check("codeql all-args: queries compiled", all(x.get("compiled") for x in res), f"{sum(bool(x.get('compiled')) for x in res)}/{len(res)}")
    ran = [x for x in res if x.get("sink_sites_outside_pkg") is not None]
    check("codeql all-args: taint and sink-site queries ran", len(ran) == len(res), f"{len(ran)}/{len(res)}")
    check(f"codeql all-args: OSVs with a taint path (measured {want})", got == want, got)


def cleanup():
    sh("k3d", "cluster", "delete", CLUSTER, check=False)


def main():
    global log
    os.makedirs(RT, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    log = open(os.path.join(OUT, "full-steps.log"), "w")
    for tool in ("go", "govulncheck", "codeql", "k3d", "kubectl", ENGINE):
        if not shutil.which(tool):
            raise SystemExit(f"{tool} not found (FULL=1 scripts/platform.sh install)")
    t0 = time.time()
    try:
        step("source", source)
        step("ci", ci)
        step("mode-b", mode_b)
        step("codeql", codeql)
    finally:
        step("cleanup", cleanup)
    json.dump({"seconds": round(time.time() - t0), "checks": checks}, open(os.path.join(OUT, "summary.json"), "w"), indent=1)
    bad = [c for c in checks if not c["ok"]]
    print(f"FULL: {len(checks) - len(bad)}/{len(checks)} checks ok, {round(time.time() - t0)} s")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
